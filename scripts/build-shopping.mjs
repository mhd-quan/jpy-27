// Walking routes for the shopping slots: from where the slot starts in the day plan, through its
// stores in order, to where it ends. Hops longer than a walk (a train ride between areas) are left
// as gaps, so the map only draws what is done on foot.
//
// Output: src/data/shopping.gen.ts  { [slotId]: { p: string[], km, min } }
// Usage: node scripts/build-shopping.mjs [--fresh]

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { place, hasPlace } from '../src/data/catalog.ts';
import { encode, haversine, lengthKm, osrm, simplify } from './geo-tools.mjs';

const root = new URL('..', import.meta.url).pathname;
const fresh = process.argv.includes('--fresh');
const file = join(root, 'research/shopping-stores.json');
const WALK_MAX_KM = 2.2;
const WALK_KMH = 4.2;
const out = {};
if (existsSync(file)) {
  const { slots = [] } = JSON.parse(readFileSync(file, 'utf8'));
  for (const s of slots) {
    const stops = [s.after, ...(s.stores ?? []), s.before].filter((id) => id && hasPlace(id)).map((id) => place(id));
    // drop repeats next to each other (start and end at the same hotel is fine)
    const pts = stops.filter((p, i) => i === 0 || p.id !== stops[i - 1].id).map((p) => [p.lat, p.lng]);
    const parts = [];
    let km = 0;
    for (let i = 1; i < pts.length; i++) {
      if (haversine(pts[i - 1], pts[i]) > WALK_MAX_KM) continue;
      let seg;
      try {
        seg = [pts[i - 1], ...(await osrm('foot', [pts[i - 1], pts[i]], { fresh })), pts[i]];
      } catch {
        seg = [pts[i - 1], pts[i]];
      }
      km += lengthKm(seg);
      parts.push(encode(simplify(seg, 0.00001)));
    }
    out[s.id] = { p: parts, km: Math.round(km * 100) / 100, min: Math.round((km / WALK_KMH) * 60) };
    console.log(`${s.id.padEnd(14)} ${String(stops.length).padStart(2)} stops  ${km.toFixed(2)} km on foot`);
  }
}
const header = '// Generated by scripts/build-shopping.mjs — do not edit by hand.\n';
writeFileSync(join(root, 'src/data/shopping.gen.ts'), `${header}export const SHOP_ROUTES: Record<string, { p: string[]; km: number; min: number }> = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} slots written`);
