// Walking times with hills for every walk on the site (see walk-tools.mjs for the model):
// plan legs on foot, detours on foot, walks around hotels and shopping routes.
//
// Output: src/data/walk.gen.ts
//   WALK_LEGS[legId], WALK_DETOURS["<day>.<placeId>"], WALK_STAYS[walkId], WALK_SHOPS[slotId]
//   each { km, up, down, walkMin, min }
// Usage: node scripts/build-walk.mjs   (after geo, detours, stays, shopping)

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DAYS, ALT_DAYS, legsOf } from '../src/data/days.ts';
import { GEO } from '../src/data/geo.gen.ts';
import { DETOURS } from '../src/data/detours.gen.ts';
import { STAYS_GEN } from '../src/data/stays.gen.ts';
import { SHOP_ROUTES } from '../src/data/shopping.gen.ts';
import { decode } from './geo-tools.mjs';
import { preloadDem, walkStats } from './walk-tools.mjs';

const root = new URL('..', import.meta.url).pathname;

const jobs = [];
for (const day of [...DAYS, ...ALT_DAYS]) {
  for (const l of legsOf(day)) {
    if (l.line !== 'walk' || !GEO[l.id]?.p) continue;
    jobs.push({ bucket: 'legs', key: l.id, pts: decode(GEO[l.id].p), from: l.from, to: l.to });
  }
}
for (const [key, d] of Object.entries(DETOURS)) {
  if (d.mode !== 'walk' || !d.p) continue;
  // a detour that starts at a station also has the platform-to-street part
  jobs.push({ bucket: 'detours', key, pts: decode(d.p), extra: d.from.onWalk || !/^(ga |Bến )/i.test(d.from.label) ? 0 : 2 });
}
for (const stay of Object.values(STAYS_GEN)) for (const w of stay.walks ?? []) jobs.push({ bucket: 'stays', key: w.id, pts: decode(w.p) });
for (const [key, r] of Object.entries(SHOP_ROUTES)) {
  const parts = r.p.map(decode).filter((p) => p.length > 1);
  if (parts.length) jobs.push({ bucket: 'shops', key, parts });
}

const all = jobs.flatMap((j) => j.pts ?? j.parts.flat());
console.log(`loading terrain for ${jobs.length} walks…`);
await preloadDem(all);

const out = { legs: {}, detours: {}, stays: {}, shops: {} };
for (const j of jobs) {
  let s;
  if (j.parts) {
    const each = j.parts.map((p) => walkStats(p));
    s = each.reduce((t, x) => ({ km: t.km + x.km, up: t.up + x.up, down: t.down + x.down, walkMin: t.walkMin + x.walkMin, min: t.min + x.min }), { km: 0, up: 0, down: 0, walkMin: 0, min: 0 });
    s.km = Math.round(s.km * 100) / 100;
  } else {
    s = walkStats(j.pts, { from: j.from, to: j.to });
    s.min += j.extra ?? 0;
  }
  out[j.bucket][j.key] = s;
}

const steep = Object.entries(out.legs)
  .filter(([, s]) => s.up >= 30)
  .sort((a, b) => b[1].up - a[1].up);
for (const [k, s] of steep) console.log(`climb ${String(s.up).padStart(4)} m  ${s.km.toFixed(2)} km  ${String(s.min).padStart(3)} min  ${k}`);

const type = '{ km: number; up: number; down: number; walkMin: number; min: number }';
const header = '// Generated by scripts/build-walk.mjs — do not edit by hand.\n';
writeFileSync(
  join(root, 'src/data/walk.gen.ts'),
  header +
    Object.entries(out)
      .map(([k, v]) => `export const WALK_${k.toUpperCase()}: Record<string, ${type}> = ${JSON.stringify(v)};`)
      .join('\n') +
    '\n',
);
console.log(`${Object.values(out).reduce((t, b) => t + Object.keys(b).length, 0)} walks written`);
