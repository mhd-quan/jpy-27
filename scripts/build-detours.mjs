// Detour routes for the "Trên đường đi" sights of each day.
//
// A sight starts from the nearest point where the day is on foot (a stop, the hotel or a walk,
// chosen in src/lib/trip.ts). When that is more than a short walk away, the nearest station on
// the day's own train lines is used instead, so a sight beside the Tōkaidō line is reached by
// getting off there. The route is OSRM on foot, or by road when the walk would pass 2.5 km.
//
// Output: src/data/detours.gen.ts  { "<day>.<placeId>": { p, km, min, mode, from } }
// Usage: node scripts/build-detours.mjs [--fresh]

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DAY_VIEWS, alongCandidates, stationLabel } from '../src/lib/trip.ts';
import { LINES } from '../src/data/lines.ts';
import { allPlaces } from '../src/data/catalog.ts';
import { nearestOnLine } from '../src/lib/geo.ts';
import { ROMAJI, encode, haversine, lengthKm, osrm, simplify, stationsForNet } from './geo-tools.mjs';

const root = new URL('..', import.meta.url).pathname;
const fresh = process.argv.includes('--fresh');
const NEAR_KM = 1.2; // matches ALONG_KM in src/lib/trip.ts
const WALK_MAX_KM = 2.5;
const WALK_KMH = 4.5;
const ROAD_KMH = 30;

// Station names the site already uses win over the romaji table.
const named = allPlaces().filter((p) => p.kind === 'station');
function stationName(st) {
  let best;
  let bestKm = 0.4;
  for (const p of named) {
    const d = haversine([st.lat, st.lng], [p.lat, p.lng]);
    if (d < bestKm) {
      bestKm = d;
      best = p.name;
    }
  }
  return stationLabel(best ?? ROMAJI[st.name] ?? st.name);
}

/** Stations that lie on the stretch of line the day actually rides. */
function stationsOnDay(v) {
  const out = [];
  for (const l of v.legs) {
    const net = LINES[l.line].net;
    if (!net || l.pts.length < 2) continue;
    for (const st of stationsForNet(net)) if (nearestOnLine([st.lat, st.lng], l.pts).km < 0.15) out.push(st);
  }
  return out;
}

const out = {};
for (const v of DAY_VIEWS) {
  let stations;
  for (const a of alongCandidates(v.day, v.legs)) {
    const sight = [a.p.lat, a.p.lng];
    let from = { label: a.from.label, pt: a.from.pt, onWalk: a.from.onWalk };
    if (a.km > NEAR_KM) {
      stations ??= stationsOnDay(v);
      let best;
      let bestKm = a.km;
      for (const st of stations) {
        const d = haversine([st.lat, st.lng], sight);
        if (d < bestKm) {
          bestKm = d;
          best = st;
        }
      }
      if (best) from = { label: stationName(best), pt: [best.lat, best.lng], onWalk: false };
    }
    const key = `${v.day.n}.${a.p.id}`;
    const fromOut = { label: from.label, lat: from.pt[0], lng: from.pt[1], onWalk: from.onWalk };
    if (haversine(from.pt, sight) < 0.05) {
      out[key] = { p: '', km: 0, min: 0, mode: 'walk', from: fromOut };
      continue;
    }
    let mode = 'walk';
    let pts;
    try {
      pts = await osrm('foot', [from.pt, sight], { fresh });
      const footKm = lengthKm(pts);
      if (footKm > WALK_MAX_KM) {
        const road = await osrm('car', [from.pt, sight], { fresh });
        // keep a trail on foot when the road goes the long way round (Satta Pass from Okitsu)
        if (lengthKm(road) < footKm * 1.8) {
          mode = 'car';
          pts = road;
        }
      }
    } catch (e) {
      console.warn(`! ${key}: ${e.message} — straight line used`);
      pts = [];
      mode = haversine(from.pt, sight) > WALK_MAX_KM ? 'car' : 'walk';
    }
    pts = [from.pt, ...pts, sight];
    const km = lengthKm(pts);
    const min = mode === 'walk' ? Math.max(1, Math.round((km / WALK_KMH) * 60)) : Math.round((km / ROAD_KMH) * 60 + 3);
    out[key] = { p: encode(simplify(pts, 0.00002)), km: Math.round(km * 100) / 100, min, mode, from: fromOut };
    console.log(`day ${String(v.day.n).padStart(2)} ${a.p.id.padEnd(26)} ${mode.padEnd(4)} ${km.toFixed(2)} km ${String(min).padStart(3)} min  from ${from.label}`);
  }
}

const header = '// Generated by scripts/build-detours.mjs — do not edit by hand.\n';
const type = "{ p: string; km: number; min: number; mode: 'walk' | 'car'; from: { label: string; lat: number; lng: number; onWalk: boolean } }";
writeFileSync(join(root, 'src/data/detours.gen.ts'), `${header}export const DETOURS: Record<string, ${type}> = ${JSON.stringify(out, null, 1)};\n`);
console.log(`\n${Object.keys(out).length} detours written`);
