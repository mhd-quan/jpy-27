// A quiet, Apple Maps–like basemap for OpenMapTiles vector tiles (OpenFreeMap),
// with terrain shading from AWS Terrain Tiles. The route and pins are drawn on top
// by map.ts; this style stays deliberately low-contrast so they lead.
import type { StyleSpecification, ExpressionSpecification, LayerSpecification } from 'maplibre-gl';

export type Theme = 'light' | 'dark';

const PALETTE = {
  light: {
    land: '#f3f2ee',
    urban: '#ecebe6',
    park: '#d8ebcf',
    wood: '#d3e6c9',
    sand: '#efe8d6',
    water: '#a9d3f1',
    waterLabel: '#4a7fa8',
    building: '#e2e1dc',
    buildingEdge: '#d6d5cf',
    road: '#ffffff',
    roadCase: '#dcdad4',
    major: '#ffffff',
    majorCase: '#d0cec7',
    motorway: '#fbd77c',
    motorwayCase: '#e6b94b',
    rail: '#c7c5bf',
    boundary: '#b9b6ae',
    label: '#3a3a3c',
    labelSoft: '#6e6e73',
    halo: 'rgba(255,255,255,0.92)',
    shadow: '#7e7a6e',
    highlight: '#ffffff',
  },
  dark: {
    land: '#1c1c1e',
    urban: '#222224',
    park: '#1d2a20',
    wood: '#1b271d',
    sand: '#2a2822',
    water: '#0f2235',
    waterLabel: '#6c92b5',
    building: '#2a2a2d',
    buildingEdge: '#333336',
    road: '#3a3a3d',
    roadCase: '#2a2a2c',
    major: '#4a4a4e',
    majorCase: '#2f2f32',
    motorway: '#6b5a2e',
    motorwayCase: '#3d3420',
    rail: '#4a4a4e',
    boundary: '#5a5a5e',
    label: '#e5e5ea',
    labelSoft: '#a1a1a6',
    halo: 'rgba(0,0,0,0.85)',
    shadow: '#000000',
    highlight: '#5a5a60',
  },
};

const name: ExpressionSpecification = ['coalesce', ['get', 'name:en'], ['get', 'name:latin'], ['get', 'name']];
const REGULAR = ['Noto Sans Regular'];
const BOLD = ['Noto Sans Bold'];
const ITALIC = ['Noto Sans Italic'];

const z = (stops: [number, number][]): ExpressionSpecification => ['interpolate', ['exponential', 1.5], ['zoom'], ...stops.flat()];

export function baseStyle(theme: Theme): StyleSpecification {
  const c = PALETTE[theme];
  const roadClass = (classes: string[]): ExpressionSpecification => ['match', ['get', 'class'], classes, true, false];
  const notTunnel: ExpressionSpecification = ['!=', ['get', 'brunnel'], 'tunnel'];

  const layers: LayerSpecification[] = [
    { id: 'background', type: 'background', paint: { 'background-color': c.land } },
    {
      id: 'landuse-urban',
      type: 'fill',
      source: 'omt',
      'source-layer': 'landuse',
      filter: ['match', ['get', 'class'], ['residential', 'suburb', 'neighbourhood', 'commercial', 'retail', 'industrial'], true, false],
      paint: { 'fill-color': c.urban, 'fill-opacity': z([[8, 0], [11, 1]]) },
    },
    {
      id: 'landcover-wood',
      type: 'fill',
      source: 'omt',
      'source-layer': 'landcover',
      filter: ['match', ['get', 'class'], ['wood', 'forest', 'grass', 'farmland', 'wetland'], true, false],
      paint: { 'fill-color': c.wood, 'fill-opacity': theme === 'light' ? 0.55 : 0.6 },
    },
    {
      id: 'landcover-sand',
      type: 'fill',
      source: 'omt',
      'source-layer': 'landcover',
      filter: ['match', ['get', 'class'], ['sand', 'rock'], true, false],
      paint: { 'fill-color': c.sand, 'fill-opacity': 0.6 },
    },
    {
      id: 'park',
      type: 'fill',
      source: 'omt',
      'source-layer': 'park',
      paint: { 'fill-color': c.park, 'fill-opacity': z([[6, 0.4], [12, 0.9]]) },
    },
    {
      id: 'hillshade',
      type: 'hillshade',
      source: 'dem',
      paint: {
        'hillshade-exaggeration': theme === 'light' ? 0.32 : 0.45,
        'hillshade-shadow-color': c.shadow,
        'hillshade-highlight-color': c.highlight,
        'hillshade-accent-color': c.shadow,
        'hillshade-illumination-direction': 315,
      },
    },
    {
      id: 'water',
      type: 'fill',
      source: 'omt',
      'source-layer': 'water',
      filter: notTunnel,
      paint: { 'fill-color': c.water, 'fill-antialias': true },
    },
    {
      id: 'waterway',
      type: 'line',
      source: 'omt',
      'source-layer': 'waterway',
      filter: notTunnel,
      paint: { 'line-color': c.water, 'line-width': z([[10, 0.6], [16, 3]]) },
    },
    {
      id: 'aeroway',
      type: 'fill',
      source: 'omt',
      'source-layer': 'aeroway',
      filter: ['==', ['geometry-type'], 'Polygon'],
      paint: { 'fill-color': c.urban, 'fill-opacity': 0.8 },
    },
    {
      id: 'building',
      type: 'fill',
      source: 'omt',
      'source-layer': 'building',
      minzoom: 14,
      paint: {
        'fill-color': c.building,
        'fill-outline-color': c.buildingEdge,
        'fill-opacity': z([[14, 0], [15.5, 1]]),
      },
    },
    // Roads: casings first, then fills, from minor to major
    {
      id: 'road-minor-case',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 13,
      filter: ['all', roadClass(['minor', 'service']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.roadCase, 'line-width': z([[13, 1], [18, 14]]) },
    },
    {
      id: 'road-major-case',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 8,
      filter: ['all', roadClass(['primary', 'secondary', 'tertiary', 'trunk']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.majorCase, 'line-width': z([[8, 0.6], [12, 3], [18, 24]]) },
    },
    {
      id: 'road-motorway-case',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 6,
      filter: ['all', roadClass(['motorway']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.motorwayCase, 'line-width': z([[6, 0.6], [12, 3.5], [18, 26]]) },
    },
    {
      id: 'road-path',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 14,
      filter: roadClass(['path', 'track']),
      paint: { 'line-color': c.roadCase, 'line-width': z([[14, 0.6], [18, 2]]), 'line-dasharray': [2, 1.5] },
    },
    {
      id: 'road-minor',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 13,
      filter: ['all', roadClass(['minor', 'service']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.road, 'line-width': z([[13, 0.5], [18, 12]]) },
    },
    {
      id: 'road-major',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 8,
      filter: ['all', roadClass(['primary', 'secondary', 'tertiary', 'trunk']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.major, 'line-width': z([[8, 0.3], [12, 2], [18, 21]]) },
    },
    {
      id: 'road-motorway',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 6,
      filter: ['all', roadClass(['motorway']), notTunnel],
      layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': c.motorway, 'line-width': z([[6, 0.4], [12, 2.4], [18, 22]]) },
    },
    {
      id: 'rail',
      type: 'line',
      source: 'omt',
      'source-layer': 'transportation',
      minzoom: 9,
      filter: ['all', roadClass(['rail', 'transit']), notTunnel],
      paint: { 'line-color': c.rail, 'line-width': z([[9, 0.6], [16, 2]]) },
    },
    {
      id: 'boundary',
      type: 'line',
      source: 'omt',
      'source-layer': 'boundary',
      filter: ['all', ['<=', ['get', 'admin_level'], 4], ['!=', ['get', 'maritime'], 1]],
      paint: { 'line-color': c.boundary, 'line-width': 0.8, 'line-dasharray': [3, 2], 'line-opacity': 0.6 },
    },
    // Labels
    {
      id: 'water-name',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'water_name',
      layout: { 'text-field': name, 'text-font': ITALIC, 'text-size': 12, 'text-max-width': 8 },
      paint: { 'text-color': c.waterLabel, 'text-halo-color': c.halo, 'text-halo-width': 1 },
    },
    {
      id: 'road-name',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'transportation_name',
      minzoom: 14,
      filter: roadClass(['primary', 'secondary', 'tertiary', 'trunk', 'minor']),
      layout: { 'symbol-placement': 'line', 'text-field': name, 'text-font': REGULAR, 'text-size': 11, 'text-max-angle': 30 },
      paint: { 'text-color': c.labelSoft, 'text-halo-color': c.halo, 'text-halo-width': 1.2 },
    },
    {
      id: 'peak',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'mountain_peak',
      minzoom: 9,
      filter: ['>', ['coalesce', ['get', 'ele'], 0], 1000],
      layout: {
        'text-field': ['concat', name, '\n', ['to-string', ['get', 'ele']], ' m'],
        'text-font': ITALIC,
        'text-size': 11,
        'text-max-width': 8,
      },
      paint: { 'text-color': c.labelSoft, 'text-halo-color': c.halo, 'text-halo-width': 1.2 },
    },
    {
      id: 'place-minor',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'place',
      minzoom: 12,
      filter: ['match', ['get', 'class'], ['suburb', 'quarter', 'neighbourhood', 'village', 'hamlet'], true, false],
      layout: { 'text-field': name, 'text-font': REGULAR, 'text-size': z([[12, 11], [16, 13]]), 'text-max-width': 8, 'text-padding': 4 },
      paint: { 'text-color': c.labelSoft, 'text-halo-color': c.halo, 'text-halo-width': 1.2 },
    },
    {
      id: 'place-town',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'place',
      minzoom: 9,
      filter: ['==', ['get', 'class'], 'town'],
      layout: { 'text-field': name, 'text-font': REGULAR, 'text-size': z([[9, 11], [14, 15]]), 'text-max-width': 8 },
      paint: { 'text-color': c.label, 'text-halo-color': c.halo, 'text-halo-width': 1.4 },
    },
    {
      id: 'place-city',
      type: 'symbol',
      source: 'omt',
      'source-layer': 'place',
      minzoom: 5,
      maxzoom: 14,
      filter: ['==', ['get', 'class'], 'city'],
      layout: { 'text-field': name, 'text-font': BOLD, 'text-size': z([[5, 11], [12, 18]]), 'text-max-width': 8 },
      paint: { 'text-color': c.label, 'text-halo-color': c.halo, 'text-halo-width': 1.6 },
    },
  ];

  return {
    version: 8,
    glyphs: 'https://tiles.openfreemap.org/fonts/{fontstack}/{range}.pbf',
    sources: {
      omt: { type: 'vector', url: 'https://tiles.openfreemap.org/planet', attribution: '© OpenFreeMap © OpenStreetMap' },
      dem: {
        type: 'raster-dem',
        tiles: ['https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png'],
        encoding: 'terrarium',
        tileSize: 256,
        maxzoom: 14,
        attribution: 'Terrain: Mapzen / AWS',
      },
    },
    layers,
  };
}
